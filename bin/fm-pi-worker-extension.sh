#!/usr/bin/env bash
# Generate the task-scoped Pi extension that owns turn-end signaling and the
# allowlisted fm-worker-telemetry.v1 projection for a newly launched worker.
#
# Usage: fm-pi-worker-extension.sh <task-id> <generation> <turn-end-file> <telemetry-file> <output-file>
# All three files must be direct children of this home's real state directory.
set -eu

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FM_ROOT="${FM_ROOT_OVERRIDE:-$(cd "$SCRIPT_DIR/.." && pwd)}"
FM_HOME="${FM_HOME:-${FM_ROOT_OVERRIDE:-$FM_ROOT}}"
STATE="${FM_STATE_OVERRIDE:-$FM_HOME/state}"

[ "$#" -eq 5 ] || {
  printf 'usage: fm-pi-worker-extension.sh <task-id> <generation> <turn-end-file> <telemetry-file> <output-file>\n' >&2
  exit 2
}
[ -d "$STATE" ] && [ ! -L "$STATE" ] || exit 1
STATE_REAL=$(cd "$STATE" && pwd -P)
for path in "$3" "$4" "$5"; do
  parent=$(cd "$(dirname "$path")" 2>/dev/null && pwd -P) || exit 1
  [ "$parent" = "$STATE_REAL" ] || exit 1
done
[ ! -L "$5" ] || exit 1
umask 077

python3 - "$1" "$2" "$3" "$4" "$5" <<'PY'
import json
import re
import sys
from pathlib import Path

task_id, generation, turn_end, telemetry, output = sys.argv[1:]
if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]{0,63}", task_id):
    raise SystemExit(1)
if not re.fullmatch(r"[a-f0-9]{32}", generation):
    raise SystemExit(1)

record = Path(telemetry)
values = {
    "__TASK_ID__": json.dumps(task_id),
    "__GENERATION__": json.dumps(generation),
    "__TURN_END__": json.dumps(turn_end),
    "__TELEMETRY__": json.dumps(telemetry),
    "__STAGING__": json.dumps(str(record.parent / f".{record.name}.tmp")),
}
template = r'''// Firstmate Pi turn-end and model/token projection; generated by fm-spawn.
// This extension reads only resolved model identifiers and finalized Usage fields.
import {
  closeSync,
  constants,
  fsyncSync,
  fstatSync,
  openSync,
  readFileSync,
  renameSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { execFile } from "node:child_process";

const TASK_ID = __TASK_ID__;
const GENERATION = __GENERATION__;
const TURN_END = __TURN_END__;
const TELEMETRY = __TELEMETRY__;
// One task-scoped staging name, so an interrupted write leaves at most one
// leftover that normal task cleanup removes by exact name.
const STAGING = __STAGING__;
const MAX_SAFE = Number.MAX_SAFE_INTEGER;
const IDENTIFIER = /^[A-Za-z0-9][A-Za-z0-9._:+/-]*$/;
let heartbeat: ReturnType<typeof setInterval> | undefined;

const emptySummary = () => ({
  schema: "fm-worker-telemetry.v1",
  taskId: TASK_ID,
  generation: GENERATION,
  harness: "pi",
  status: "fresh",
  observedAt: new Date().toISOString(),
  coverage: "full_worker",
  final: false,
  model: { provider: null as string | null, id: null as string | null },
  tokens: {
    input: 0,
    output: 0,
    cacheRead: 0,
    cacheWrite: 0,
    reasoningOutput: null,
    total: 0,
    totalSemantics: "source_reported",
  },
});
let summary = emptySummary();

function safeIdentifier(value: unknown, maximum: number): string | null {
  return typeof value === "string" && value.length <= maximum && IDENTIFIER.test(value)
    ? value
    : null;
}

function safeInteger(value: unknown): number | null {
  return Number.isSafeInteger(value) && (value as number) >= 0 ? (value as number) : null;
}

function safeAdd(left: number, right: number): number | null {
  const value = left + right;
  return Number.isSafeInteger(value) && value >= 0 && value <= MAX_SAFE ? value : null;
}

function restore(): void {
  let fd: number | undefined;
  try {
    fd = openSync(TELEMETRY, constants.O_RDONLY | constants.O_NOFOLLOW);
    const info = fstatSync(fd);
    if (!info.isFile() || info.size > 16 * 1024 || (info.mode & 0o077) !== 0) return;
    if (typeof process.getuid === "function" && info.uid !== process.getuid()) return;
    const raw = readFileSync(fd, { encoding: "utf8" });
    if (Buffer.byteLength(raw) > 16 * 1024) return;
    const value = JSON.parse(raw);
    if (value?.schema !== "fm-worker-telemetry.v1" || value?.taskId !== TASK_ID || value?.generation !== GENERATION || value?.harness !== "pi") return;
    const provider = value.model?.provider === null ? null : safeIdentifier(value.model?.provider, 40);
    const modelId = value.model?.id === null ? null : safeIdentifier(value.model?.id, 120);
    if (provider !== null && modelId === null) return;
    const tokens = value.tokens;
    const input = safeInteger(tokens?.input);
    const output = safeInteger(tokens?.output);
    const cacheRead = safeInteger(tokens?.cacheRead);
    const cacheWrite = safeInteger(tokens?.cacheWrite);
    const total = safeInteger(tokens?.total);
    const hasAll = [input, output, cacheRead, cacheWrite, total].every((item) => item !== null);
    if (value.status !== "unavailable" && !hasAll) return;
    if (hasAll) {
      summary.tokens = {
        input,
        output,
        cacheRead,
        cacheWrite,
        reasoningOutput: null,
        total,
        totalSemantics: "source_reported",
      };
    }
    summary.model = { provider, id: modelId };
    if (value.status === "partial" && value.coverage === "since_observed") {
      summary.status = "partial";
      summary.coverage = "since_observed";
    }
  } catch {
    // Telemetry is passive. A malformed/missing prior record starts a new projection.
  } finally {
    if (fd !== undefined) {
      try { closeSync(fd); } catch { /* passive cleanup */ }
    }
  }
}

function openStaging(): number {
  const flags = constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | constants.O_NOFOLLOW;
  try {
    return openSync(STAGING, flags, 0o600);
  } catch {
    unlinkSync(STAGING);
    return openSync(STAGING, flags, 0o600);
  }
}

function writeSummary(): void {
  let staged = false;
  try {
    summary.observedAt = new Date().toISOString();
    const encoded = `${JSON.stringify(summary)}\n`;
    if (Buffer.byteLength(encoded) > 16 * 1024) return;
    const fd = openStaging();
    staged = true;
    try {
      writeFileSync(fd, encoded, "utf8");
      fsyncSync(fd);
    } finally {
      closeSync(fd);
    }
    renameSync(STAGING, TELEMETRY);
    staged = false;
  } catch {
    if (staged) {
      try { unlinkSync(STAGING); } catch { /* passive cleanup */ }
    }
  }
}

function updateModel(model: unknown): void {
  const value = model as { provider?: unknown; id?: unknown } | null;
  const provider = safeIdentifier(value?.provider, 40);
  const id = safeIdentifier(value?.id, 120);
  if (provider !== null && id !== null) summary.model = { provider, id };
}

function markPartial(): void {
  summary.status = "partial";
  summary.coverage = "since_observed";
  writeSummary();
}

export default function (pi: any) {
  // The established turn-end signal is registered first and never shares a
  // failure path with the optional telemetry projection.
  pi.on("turn_end", () => execFile("touch", [TURN_END], () => undefined));

  const project = (name: string, handler: (event: any, ctx: any) => void): void => {
    try {
      pi.on(name, (event: any, ctx: any) => {
        try {
          handler(event, ctx);
        } catch { /* telemetry is passive */ }
      });
    } catch { /* telemetry is passive */ }
  };

  project("session_start", (_event: unknown, ctx: any) => {
    restore();
    summary.final = false;
    updateModel(ctx?.model);
    writeSummary();
    if (heartbeat) clearInterval(heartbeat);
    heartbeat = setInterval(writeSummary, 30_000);
    heartbeat.unref?.();
  });

  project("model_select", (event: any) => {
    updateModel(event?.model);
    writeSummary();
  });

  project("message_end", (event: any) => {
    const message = event?.message;
    if (message?.role !== "assistant") return;
    const usage = message?.usage;
    const input = safeInteger(usage?.input);
    const output = safeInteger(usage?.output);
    const cacheRead = safeInteger(usage?.cacheRead);
    const cacheWrite = safeInteger(usage?.cacheWrite);
    const total = safeInteger(usage?.totalTokens);
    if ([input, output, cacheRead, cacheWrite, total].some((item) => item === null)) {
      markPartial();
      return;
    }
    const next = {
      input: safeAdd(summary.tokens.input, input as number),
      output: safeAdd(summary.tokens.output, output as number),
      cacheRead: safeAdd(summary.tokens.cacheRead, cacheRead as number),
      cacheWrite: safeAdd(summary.tokens.cacheWrite, cacheWrite as number),
      total: safeAdd(summary.tokens.total, total as number),
    };
    if (Object.values(next).some((item) => item === null)) {
      markPartial();
      return;
    }
    summary.tokens = {
      input: next.input as number,
      output: next.output as number,
      cacheRead: next.cacheRead as number,
      cacheWrite: next.cacheWrite as number,
      reasoningOutput: null,
      total: next.total as number,
      totalSemantics: "source_reported",
    };
    const provider = safeIdentifier(message?.provider, 40);
    const id = safeIdentifier(message?.model, 120);
    if (provider !== null && id !== null) summary.model = { provider, id };
    if (summary.status !== "partial") {
      summary.status = "fresh";
      summary.coverage = "full_worker";
    }
    writeSummary();
  });

  project("session_shutdown", () => {
    if (heartbeat) clearInterval(heartbeat);
    heartbeat = undefined;
    summary.final = true;
    writeSummary();
  });
}
'''
for marker, value in values.items():
    template = template.replace(marker, value)
Path(output).write_text(template, encoding="utf-8")
Path(output).chmod(0o600)
PY
